import { build } from 'esbuild';
import { mkdir, writeFile } from 'node:fs/promises';
import { dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

/** The sandbox module that runs agent-written Playwright scripts: `runner.js` with `@cloudflare/playwright` bundled in,
 * importing the script as `./script.js`. Built at release time (and for tests), never committed: it is about 2 MB. */
export async function buildBrowserRunner(): Promise<string> {
  const result = await build({
    entryPoints: [fileURLToPath(new URL('./runner.js', import.meta.url))],
    bundle: true, write: false, format: 'esm', platform: 'browser', target: 'es2024', minify: true,
    conditions: ['workerd', 'worker', 'browser'],
    external: ['cloudflare:*', 'node:*', './script.js'],
    logLevel: 'silent',
  });
  const [output] = result.outputFiles;
  if (!output) throw new Error('Browser runner build produced no module');
  return output.text;
}

/** Writes the runner as a module exporting `BROWSER_RUNNER_SOURCE`, for a Worker build to import. */
export async function writeBrowserRunner(path: string | URL): Promise<void> {
  const target = typeof path === 'string' ? path : fileURLToPath(path);
  await mkdir(dirname(target), { recursive: true });
  await writeFile(target, `// Generated by @gitspace/browser-runner; not committed.\nexport const BROWSER_RUNNER_SOURCE = ${JSON.stringify(await buildBrowserRunner())};\n`);
}
