// Bundles the service worker and the popup into `bundle.generated.ts`, which the account Worker serves; run
// `bun run build` after changing either. `test/bundle.test.ts` fails while the generated module is stale.
import { join } from 'node:path';
import { BROWSER_EXTENSION_PROTOCOL } from '@gitspace/protocol-runtime';

export async function generatedBundle(): Promise<string> {
  const result = await Bun.build({ entrypoints: [join(import.meta.dir, 'background.js')], target: 'browser', format: 'esm',
    // A plain script (`background.js` exports nothing): Chrome runs it as a classic service worker. The protocol
    // number is defined, not imported: importing it would bundle protocol-runtime and its schemas.
    define: { BROWSER_EXTENSION_PROTOCOL: String(BROWSER_EXTENSION_PROTOCOL) } });
  if (!result.success) throw new AggregateError(result.logs, 'Extension bundle failed');
  const [output] = result.outputs;
  if (!output) throw new Error('Extension bundle produced no output');
  const popup = await Bun.file(join(import.meta.dir, 'popup.js')).text();
  return `// Generated by \`bun run build\` (src/build.ts) from background.js and popup.js. Do not edit.
export const BACKGROUND_SOURCE = ${JSON.stringify(await output.text())};
export const POPUP_SOURCE = ${JSON.stringify(popup)};
`;
}

if (import.meta.main) await Bun.write(join(import.meta.dir, 'bundle.generated.ts'), await generatedBundle());
