// Bundles the service worker, the offscreen recorder and the popup (React, with its stylesheet compiled by Tailwind)
// into `bundle.generated.ts`, which the account Worker serves; run `bun run build` after changing any of them.
// `test/bundle.test.ts` fails while the generated module is stale.
import { dirname, join } from 'node:path';
import { compile, optimize } from '@tailwindcss/node';
import { Scanner } from '@tailwindcss/oxide';
import type { BunPlugin } from 'bun';
import { BROWSER_EXTENSION_PROTOCOL } from '@gitspace/protocol-runtime';

/** Where `@/…` imports go, as in the web apps: the Fluid components of `@gitspace/ui`, imported one module at a time,
 * so the popup bundles only the components it renders. */
const FLUID = join(dirname(Bun.resolveSync('@gitspace/ui/fluid-theme.css', import.meta.dir)), 'fluid-vendor');
const fluidAlias: BunPlugin = {
  name: 'fluid-alias',
  setup(build) { build.onResolve({ filter: /^@\// }, args => ({ path: Bun.resolveSync(join(FLUID, args.path.slice(2)), dirname(args.importer)) })); },
};
/** The theme's Inter, served by the account at this path; `extensionFiles` puts the account's origin where the
 * stylesheet has `POPUP_FONT_ORIGIN`. */
const POPUP_FONT_PATH = '/fonts/InterVariable.ttf';
const POPUP_FONT_ORIGIN = '__GITSPACE_ACCOUNT_ORIGIN__';

/** One plain script (it exports nothing): Chrome runs the service worker as a classic one and the offscreen page's
 * script as a classic script. The protocol number is defined, not imported: importing it would bundle
 * protocol-runtime and its schemas. */
async function bundled(entry: string): Promise<string> {
  const result = await Bun.build({ entrypoints: [join(import.meta.dir, entry)], target: 'browser', format: 'esm', define: { BROWSER_EXTENSION_PROTOCOL: String(BROWSER_EXTENSION_PROTOCOL) } });
  if (!result.success) throw new AggregateError(result.logs, `Extension bundle of ${entry} failed`);
  const [output] = result.outputs;
  if (!output) throw new Error(`Extension bundle of ${entry} produced no output`);
  return output.text();
}

/** The popup's script: React and the Fluid components, minified into one classic script (MV3 pages run no inline or
 * remote code). */
async function popupScript(): Promise<string> {
  const result = await Bun.build({ entrypoints: [join(import.meta.dir, 'popup.tsx')], target: 'browser', format: 'iife', minify: true, plugins: [fluidAlias], define: { 'process.env.NODE_ENV': '"production"' } });
  if (!result.success) throw new AggregateError(result.logs, 'Extension bundle of popup.tsx failed');
  const [output] = result.outputs;
  if (!output) throw new Error('Extension bundle of popup.tsx produced no output');
  return output.text();
}

/** The popup's stylesheet: `popup.css` (GitSpace's Fluid theme) with the Tailwind classes of its own sources and of
 * the popup. The theme also names the web apps' sources (patterns reaching out of its package), which the popup never
 * renders, so those are not scanned. Its Inter comes from the account (`POPUP_FONT_PATH`). */
async function popupStyles(): Promise<string> {
  const tailwind = Bun.resolveSync('tailwindcss/index.css', import.meta.dir);
  const compiler = await compile(await Bun.file(join(import.meta.dir, 'popup.css')).text(), {
    base: import.meta.dir, onDependency: () => {},
    customCssResolver: async id => id === 'tailwindcss' ? tailwind : undefined,
  });
  const scanner = new Scanner({ sources: compiler.sources.filter(source => !source.pattern.startsWith('../')) });
  const css = optimize(compiler.build(scanner.scan()), { minify: true }).code;
  const font = 'url(./fluid-vendor/InterVariable.ttf)';
  if (!css.includes(font)) throw new Error(`The Fluid theme no longer loads Inter from ${font}; update popupStyles`);
  return css.replaceAll(font, `url(${POPUP_FONT_ORIGIN}${POPUP_FONT_PATH})`);
}

export async function generatedBundle(): Promise<string> {
  return `// Generated by \`bun run build\` (src/build.ts) from background.js, offscreen.js, popup.tsx and popup.css. Do not edit.
export const BACKGROUND_SOURCE = ${JSON.stringify(await bundled('background.js'))};
export const OFFSCREEN_SOURCE = ${JSON.stringify(await bundled('offscreen.js'))};
export const POPUP_SOURCE = ${JSON.stringify(await popupScript())};
export const POPUP_STYLES = ${JSON.stringify(await popupStyles())};
export const POPUP_FONT_ORIGIN = ${JSON.stringify(POPUP_FONT_ORIGIN)};
`;
}

if (import.meta.main) await Bun.write(join(import.meta.dir, 'bundle.generated.ts'), await generatedBundle());
