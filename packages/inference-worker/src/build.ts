import { build } from 'esbuild';
import { builtinModules } from 'node:module';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

/** The inference worker as one module, with pi-ai, every provider and GitSpace's models layer bundled in. Built at
 * release time (and for tests), never committed. It imports `./xxhash.wasm`, which the loader is given beside it. */
export async function buildInferenceWorker(): Promise<{ source: string; wasm: Uint8Array }> {
  const result = await build({
    entryPoints: [fileURLToPath(new URL('./index.ts', import.meta.url))],
    bundle: true, write: false, format: 'esm', platform: 'browser', target: 'es2024', minify: true,
    conditions: ['workerd', 'worker', 'browser'], mainFields: ['browser', 'module', 'main'],
    external: ['cloudflare:*', 'node:*', '*.wasm', ...builtinModules.filter(name => !name.startsWith('_'))],
    logLevel: 'silent',
  });
  const [output] = result.outputFiles;
  if (!output) throw new Error('Inference worker build produced no module');
  const workerd = createRequire(import.meta.url).resolve('xxhash-wasm', { paths: [fileURLToPath(new URL('..', import.meta.url))] });
  const wasm = new Uint8Array(await readFile(join(dirname(workerd), '..', 'workerd', 'xxhash.wasm')));
  return { source: output.text, wasm };
}

/** Writes the worker as a module exporting `INFERENCE_WORKER_SOURCE` and its wasm (`INFERENCE_WORKER_WASM`, base64),
 * for the tenant build to import and hand to its Worker Loader. */
export async function writeInferenceWorker(path: string | URL): Promise<void> {
  const target = typeof path === 'string' ? path : fileURLToPath(path);
  const { source, wasm } = await buildInferenceWorker();
  await mkdir(dirname(target), { recursive: true });
  await writeFile(target, `// Generated by @gitspace/inference-worker; not committed.\nexport const INFERENCE_WORKER_SOURCE = ${JSON.stringify(source)};\nexport const INFERENCE_WORKER_WASM = ${JSON.stringify(Buffer.from(wasm).toString('base64'))};\n`);
}
